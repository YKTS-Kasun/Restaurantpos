    public function Tablenoinsertupdate(){
        $this->db->trans_begin();

        $userID=$_SESSION['userid'];

        $tableno=$this->input->post('tableno');
     

        $recordOption=$this->input->post('recordOption');
        if(!empty($this->input->post('recordID'))){$recordID=$this->input->post('recordID');}

