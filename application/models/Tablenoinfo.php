    public function Tablenoedit(){
        $recordID=$this->input->post('recordID');

        $this->db->select('*');
        $this->db->from('tbl_table_no');
        $this->db->where('idtbl_table_no', $recordID);
        $this->db->where('status', 1);

        $respond=$this->db->get();

        $obj=new stdClass();
        $obj->id=$respond->row(0)->idtbl_table_no;
        $obj->tableno=$respond->row(0)->tableno;
        

        echo json_encode($obj);
    }
