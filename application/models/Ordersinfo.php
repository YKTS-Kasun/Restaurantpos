    public function Ordertransfertokitchen(){
        $this->db->trans_begin();

        $userID=$_SESSION['userid'];
        $recordID=$this->input->post('recordID');
        $updatedatetime=date('Y-m-d H:i:s');

        $this->db->select('*');
        $this->db->from('tbl_res_orderdetail');
        $this->db->where('tbl_res_order_idtbl_res_order', $recordID);
        $this->db->where('status', 1);

        $respond=$this->db->get();

        $data = array(
            'date'=> date('Y-m-d'), 
            'tableid'=> '0', 
            'orderid'=> $recordID, 
            'status'=> '1', 
            'insertdatetime'=> $updatedatetime, 
            'tbl_res_user_idtbl_res_user'=> $userID
        );

        $this->db->insert('tbl_res_kot', $data);
        $kotID=$this->db->insert_id();

        foreach($respond->result() as $loadrequest){
            $datadetail = array(
                'qty'=> $loadrequest->qty, 
                'notes'=> '', 
                'status'=> '1', 
                'insertdatetime'=> $updatedatetime, 
                'tbl_res_user_idtbl_res_user'=> $userID, 
                'tbl_res_kot_idtbl_res_kot'=> $kotID, 
                'tbl_res_item_idtbl_res_item'=> $loadrequest->tbl_res_item_idtbl_res_item
            );
    
            $this->db->insert('tbl_res_kot_detail', $datadetail);
        }
        
        $this->db->trans_complete();

        if ($this->db->trans_status() === TRUE) {
            $this->db->trans_commit();
            
            $actionObj=new stdClass();
            $actionObj->icon='fas fa-save';
            $actionObj->title='';
            $actionObj->message='Record Added Successfully';
            $actionObj->url='';
            $actionObj->target='_blank';
            $actionObj->type='success';

            $actionJSON=json_encode($actionObj);

            $obj=new stdClass();
            $obj->status=1;          
            $obj->action=$actionJSON;  
            
            echo json_encode($obj);
        } else {
            $this->db->trans_rollback();

            $actionObj=new stdClass();
            $actionObj->icon='fas fa-exclamation-triangle';
            $actionObj->title='';
            $actionObj->message='Record Error';
            $actionObj->url='';
            $actionObj->target='_blank';
            $actionObj->type='danger';

            $actionJSON=json_encode($actionObj);

            $obj=new stdClass();
            $obj->status=0;          
            $obj->action=$actionJSON;  
            
            echo json_encode($obj);
        }
    }
